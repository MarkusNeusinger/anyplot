"""Build the single-file mirror of the adaptability checker for the workflow runner.

The pipeline runs its helper scripts from a copy under `$RUNNER_TEMP` with the runner's
system Python, where `core` is not importable (the pattern of
`automation/scripts/regen_gate.py`). `automation/scripts/adaptability_check.py` is
therefore one file: the bodies of `core/spec_roles.py` and `core/adaptability.py`
verbatim, behind one docstring and the union of their standard-library imports.
`tests/unit/core/test_adaptability_mirror.py` fails when the file differs from what
`build_mirror` produces, so a change to either module is followed by::

    uv run python -m core.adaptability_mirror

which rewrites the mirror (`--check` only compares, exit 1 on a difference).
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections.abc import Sequence
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (Path("core/spec_roles.py"), Path("core/adaptability.py"))
MIRROR = Path("automation/scripts/adaptability_check.py")

HEADER = '''#!/usr/bin/env python3
"""The adaptability checker as one standard-library file, for the workflow runner.

GENERATED by `uv run python -m core.adaptability_mirror` from core/spec_roles.py and
core/adaptability.py; edit those modules, never this file. The module docstring of
core/adaptability.py describes the rules and the record; this copy runs where `core`
is not importable:

    python3 adaptability_check.py check plots/<spec>/implementations/python/<library>.py
    python3 adaptability_check.py report plots/

tests/unit/core/test_adaptability_mirror.py keeps it identical to the build.
"""
'''


def _split(path: Path) -> tuple[list[ast.Import | ast.ImportFrom], str]:
    """A module's import statements (`__future__` and `core` imports dropped) and its body text.

    The body starts after the last top-level import, so the module docstring and imports
    are left out and every definition, comment and blank line after them is kept.
    """
    text = path.read_text(encoding="utf-8")
    tree = ast.parse(text)
    imports: list[ast.Import | ast.ImportFrom] = []
    last = 0
    for node in tree.body:
        if isinstance(node, ast.Import | ast.ImportFrom):
            last = node.end_lineno or node.lineno
            module = node.module if isinstance(node, ast.ImportFrom) else None
            if module == "__future__" or (module or "").split(".")[0] == "core":
                continue
            imports.append(node)
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            continue  # the module docstring
        else:
            break
    body = "\n".join(text.splitlines()[last:]).strip("\n")
    return imports, body


def _name_order(name: str) -> tuple[int, str]:
    """ruff's isort `order-by-type`: constants, then classes, then everything else."""
    if name.isupper() and len(name) > 1:
        return 0, name
    if name[:1].isupper():
        return 1, name
    return 2, name


def _merged_imports(nodes: Sequence[ast.Import | ast.ImportFrom]) -> list[str]:
    """One `import x` line per module and one `from m import a, b` line per module, sorted as ruff sorts them."""
    plain: set[str] = set()
    froms: dict[str, set[str]] = {}
    for node in nodes:
        if isinstance(node, ast.Import):
            for alias in node.names:
                plain.add(alias.name if alias.asname is None else f"{alias.name} as {alias.asname}")
        else:
            names = froms.setdefault(node.module or "", set())
            for alias in node.names:
                names.add(alias.name if alias.asname is None else f"{alias.name} as {alias.asname}")
    lines = [f"import {module}" for module in sorted(plain)]
    for module in sorted(froms):
        ordered = sorted(froms[module], key=lambda item: _name_order(item.split(" as ")[0]))
        lines.append(f"from {module} import {', '.join(ordered)}")
    return lines


def build_mirror(root: Path = ROOT) -> str:
    """The mirror's text: header, `__future__`, the merged imports, then each module's body in order."""
    imports: list[ast.Import | ast.ImportFrom] = []
    bodies: list[str] = []
    for source in SOURCES:
        module_imports, body = _split(root / source)
        imports.extend(module_imports)
        rule = "-" * (100 - len(source.as_posix()))
        bodies.append(f"# --- {source.as_posix()} {rule}\n\n{body}")
    head = HEADER.rstrip("\n") + "\n\nfrom __future__ import annotations\n\n" + "\n".join(_merged_imports(imports))
    return "\n\n\n".join([head, *bodies]) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m core.adaptability_mirror", description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare only; exit 1 when the mirror is stale")
    args = parser.parse_args(argv)
    text = build_mirror()
    target = ROOT / MIRROR
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"{MIRROR} is stale: run `uv run python -m core.adaptability_mirror`")
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {MIRROR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
