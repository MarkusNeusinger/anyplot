def to_path(rings):
    """Join rings into one projected line series; (None, None) lifts the pen between rings."""
    path = []
    for ring in rings:
        x, y = robinson(*zip(*ring, strict=True))
        path += list(zip(x.tolist(), y.tolist(), strict=True)) + [(float(x[-1]), None)]
    return path


