type XY = [number, number];
type Vec3 = [number, number, number];

const sinLat0 = Math.sin(ORTHO_LAT0 * DEG2RAD);
const cosLat0 = Math.cos(ORTHO_LAT0 * DEG2RAD);

// Insert vertices so that no segment spans more than MAX_STEP_DEG; straight edges then curve with the projection
function densify(pts: LonLat[]): LonLat[] {
  const out: LonLat[] = [pts[0]];
  for (let i = 1; i < pts.length; i++) {
    const [lon0, lat0] = pts[i - 1];
    const [lon1, lat1] = pts[i];
    const n = Math.ceil(Math.max(Math.abs(lon1 - lon0), Math.abs(lat1 - lat0)) / MAX_STEP_DEG);
    for (let k = 1; k <= n; k++) out.push([lon0 + ((lon1 - lon0) * k) / n, lat0 + ((lat1 - lat0) * k) / n]);
  }
  return out;
}

// Auxiliary angle θ of Mollweide: 2θ + sin 2θ = π sin φ (Newton iteration)
function mollweideTheta(phi: number): number {
  if (Math.abs(Math.abs(phi) - Math.PI / 2) < 1e-7) return Math.sign(phi) * (Math.PI / 2);
  let theta = phi;
  const target = Math.PI * Math.sin(phi);
  for (let it = 0; it < 12; it++) {
    const d = (2 * theta + Math.sin(2 * theta) - target) / (2 + 2 * Math.cos(2 * theta));
    theta -= d;
    if (Math.abs(d) < 1e-9) break;
  }
  return theta;
}

const flatProjections: Record<string, (p: LonLat) => XY> = {
  Mercator: ([lon, lat]) => {
    const phi = Math.max(-MERCATOR_LAT_CLIP, Math.min(MERCATOR_LAT_CLIP, lat)) * DEG2RAD;
    return [lon * DEG2RAD, Math.log(Math.tan(Math.PI / 4 + phi / 2))];
  },
  Mollweide: ([lon, lat]) => {
    const theta = mollweideTheta(lat * DEG2RAD);
    return [((2 * SQRT2) / Math.PI) * lon * DEG2RAD * Math.cos(theta), SQRT2 * Math.sin(theta)];
  },
};

// Orthographic point as a unit vector: x, y on the image plane, z ≥ 0 on the visible hemisphere
function orthoVec([lon, lat]: LonLat): Vec3 {
  const lam = (lon - ORTHO_LON0) * DEG2RAD;
  const phi = lat * DEG2RAD;
  return [
    Math.cos(phi) * Math.sin(lam),
    cosLat0 * Math.sin(phi) - sinLat0 * Math.cos(phi) * Math.cos(lam),
    sinLat0 * Math.sin(phi) + cosLat0 * Math.cos(phi) * Math.cos(lam),
  ];
}

// Where segment a→b crosses the horizon, pushed out onto the limb circle
function limbPoint(a: Vec3, b: Vec3): XY {
  const s = a[2] / (a[2] - b[2]);
  const x = a[0] + s * (b[0] - a[0]);
  const y = a[1] + s * (b[1] - a[1]);
  const r = Math.hypot(x, y);
  return [x / r, y / r];
}

// Intermediate points along the limb from p to q, the short way round
function limbArc(p: XY, q: XY): XY[] {
  const a0 = Math.atan2(p[1], p[0]);
  let d = Math.atan2(q[1], q[0]) - a0;
  d -= 2 * Math.PI * Math.round(d / (2 * Math.PI));
  const n = Math.ceil(Math.abs(d) / LIMB_STEP_RAD);
  const arc: XY[] = [];
  for (let k = 1; k < n; k++) arc.push([Math.cos(a0 + (d * k) / n), Math.sin(a0 + (d * k) / n)]);
  return arc;
}

// Polyline → projected runs; on the globe a line is cut where it passes behind the horizon
function projectLine(projId: string, pts: LonLat[]): XY[][] {
  const dense = densify(pts);
  if (projId !== "Orthographic") return [dense.map(flatProjections[projId])];
  const v = dense.map(orthoVec);
  const runs: XY[][] = [];
  let cur: XY[] = [];
  for (let i = 0; i < v.length; i++) {
    const p = v[i];
    const prev = v[i - 1];
    if (p[2] >= 0) {
      if (prev && prev[2] < 0) cur.push(limbPoint(prev, p));
      cur.push([p[0], p[1]]);
    } else if (prev && prev[2] >= 0) {
      cur.push(limbPoint(prev, p));
      runs.push(cur);
      cur = [];
    }
  }
  runs.push(cur);
  return runs.filter((r) => r.length > 1);
}

// Closed ring → projected ring; on the globe it is clipped to the visible hemisphere (Sutherland–Hodgman)
// and every stretch that runs behind the horizon is closed along the limb arc instead of a chord
function projectRing(projId: string, pts: LonLat[]): XY[] {
  const dense = densify([...pts, pts[0]]);
  if (projId !== "Orthographic") return dense.map(flatProjections[projId]);
  const v = dense.map(orthoVec);
  const out: Array<{ p: XY; onLimb: boolean }> = [];
  for (let i = 1; i < v.length; i++) {
    const a = v[i - 1];
    const b = v[i];
    if (b[2] >= 0) {
      if (a[2] < 0) out.push({ p: limbPoint(a, b), onLimb: true });
      out.push({ p: [b[0], b[1]], onLimb: false });
    } else if (a[2] >= 0) {
      out.push({ p: limbPoint(a, b), onLimb: true });
    }
  }
  return out.flatMap((cur, i) => {
    const next = out[(i + 1) % out.length];
    return cur.onLimb && next.onLimb ? [cur.p, ...limbArc(cur.p, next.p)] : [cur.p];
  });
}

// Graticule, equator, prime meridian and Tissot circles (geodesic circles of equal radius)
const graticule: LonLat[][] = [];
for (let lat = -60; lat <= 60; lat += GRATICULE_STEP_DEG) {
  if (lat !== 0) graticule.push([[-180, lat], [180, lat]]);
}
for (let lon = -150; lon <= 150; lon += GRATICULE_STEP_DEG) {
  if (lon !== 0) graticule.push([[lon, -90], [lon, 90]]);
}
const equator: LonLat[] = [[-180, 0], [180, 0]];
const primeMeridian: LonLat[] = [[0, -90], [0, 90]];

const tissotRings: LonLat[][] = [];
for (let latC = -60; latC <= 60; latC += GRATICULE_STEP_DEG) {
  for (let lonC = -120; lonC <= 120; lonC += GRATICULE_STEP_DEG * 2) {
    const phi1 = latC * DEG2RAD;
    const ring: LonLat[] = [];
    for (let i = 0; i < TISSOT_STEPS; i++) {
      const brng = (i / TISSOT_STEPS) * 2 * Math.PI;
      const phi2 = Math.asin(
        Math.sin(phi1) * Math.cos(TISSOT_RADIUS_RAD) + Math.cos(phi1) * Math.sin(TISSOT_RADIUS_RAD) * Math.cos(brng),
      );
      const dLam = Math.atan2(
        Math.sin(brng) * Math.sin(TISSOT_RADIUS_RAD) * Math.cos(phi1),
        Math.cos(TISSOT_RADIUS_RAD) - Math.sin(phi1) * Math.sin(phi2),
      );
      ring.push([lonC + dLam / DEG2RAD, phi2 / DEG2RAD]);
    }
    tissotRings.push(ring);
  }
}

const areas = data.filter((d) => d[FEATURE_KIND] !== "border");
const borders = data.filter((d) => d[FEATURE_KIND] === "border");

function outlineOf(projId: string): XY[] {
  const steps = 120;
  if (projId === "Mercator") {
    const yMax = flatProjections.Mercator([0, MERCATOR_LAT_CLIP])[1];
    return [[-Math.PI, -yMax], [Math.PI, -yMax], [Math.PI, yMax], [-Math.PI, yMax]];
  }
  const [rx, ry] = projId === "Mollweide" ? [2 * SQRT2, SQRT2] : [1, 1];
  return Array.from({ length: steps }, (_, i) => [rx * Math.cos((i / steps) * 2 * Math.PI), ry * Math.sin((i / steps) * 2 * Math.PI)]);
}

const bundles = PROJECTIONS.map((meta) => {
  const id = meta.id;
  const outline = outlineOf(id);
  const xs = outline.map((p) => p[0]);
  const ys = outline.map((p) => p[1]);
  return {
    ...meta,
    outline,
    bboxMin: [Math.min(...xs), Math.min(...ys)],
    bboxMax: [Math.max(...xs), Math.max(...ys)],
    // Land and lakes share one even-odd fill, so a lake inside a landmass reads as water
    landFill: areas.map((d) => projectRing(id, d[VERTICES])).filter((r) => r.length > 2),
    coastlines: areas.flatMap((d) => projectLine(id, [...d[VERTICES], d[VERTICES][0]])),
    borders: borders.flatMap((d) => projectLine(id, d[VERTICES])),
    graticule: graticule.flatMap((line) => projectLine(id, line)),
    equator: projectLine(id, equator),
    primeMeridian: projectLine(id, primeMeridian),
    tissot: tissotRings.map((ring) => projectRing(id, ring)).filter((r) => r.length > 2),
  };
});

